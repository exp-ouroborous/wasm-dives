/** Inline style that themes a card page (see card.css) in a language's colours. */
export function languageStyle(id) {
  const { color, dark, keyline } = LANGUAGES[id];
  return `--accent: ${color}; --accent-dark: ${dark}; --keyline: ${keyline}`;
}

/** An <svg> logo element, built without HTML strings. */
export function languageLogo(id, doc = document) {
  const { logo } = LANGUAGES[id];
  const svg = doc.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("role", "img");
  const title = doc.createElementNS("http://www.w3.org/2000/svg", "title");
  title.textContent = logo.title;
  const path = doc.createElementNS("http://www.w3.org/2000/svg", "path");
  path.setAttribute("d", logo.path);
  svg.append(title, path);
  return svg;
}
