import { createHash } from "node:crypto";
import { execFile } from "node:child_process";
import { cp, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, relative, sep } from "node:path";
import { promisify } from "node:util";

/**
 * A short content hash over a runtime's files (path and bytes), used as its
 * vendored directory name: /run/vendor/* is served immutable, so any change
 * to the runtime must land at a new URL.
 */
export function runtimeId(files) {
  const hash = createHash("sha256");
  for (const { path, bytes } of [...files].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))) {
    hash.update(`${path}\0${bytes.length}\0`);
    hash.update(bytes);
  }
  return hash.digest("hex").slice(0, 12);
}

/** The module the worker imports to reach this build's dotnet.js. */
export function runtimeModule(fromDir, dotnetJs) {
  const specifier = relative(fromDir, dotnetJs).split(sep).join("/");
  return `// Generated by scripts/dotnet.mjs: this build's .NET runtime.\nexport { dotnet } from "${specifier.startsWith(".") ? specifier : `./${specifier}`}";\n`;
}

async function readTree(dir) {
  const entries = await readdir(dir, { withFileTypes: true, recursive: true });
  return Promise.all(
    entries
      .filter((entry) => entry.isFile())
      .map(async (entry) => {
        const file = join(entry.parentPath, entry.name);
        return { path: relative(dir, file).split(sep).join("/"), bytes: await readFile(file) };
      }),
  );
}

/**
 * Publish a .NET WebAssembly project (`dotnet publish`, SDK pinned by its
 * global.json) and vendor its _framework into dist/<vendorDir>/<runtimeId>/,
 * then write <module> re-exporting its dotnet.js. Returns the dist-relative
 * entries for the manifest group.
 */
export async function publishDotnetRuntime(root, distDir, spec) {
  const out = await mkdtemp(join(tmpdir(), "wasm-dives-dotnet-"));
  try {
    await promisify(execFile)("dotnet", ["publish", join(root, spec.project), "-c", "Release", "-o", out, "--nologo"], {
      cwd: join(root, spec.project, ".."),
      maxBuffer: 64 * 1024 * 1024,
    }).catch((error) => {
      throw new Error(`dotnet publish ${spec.project} failed (needs the .NET SDK in its global.json):\n${error.stdout ?? ""}${error.stderr ?? error.message}`);
    });
    const framework = join(out, "wwwroot/_framework");
    const vendored = `${spec.vendorDir}/${runtimeId(await readTree(framework))}`;
    await cp(framework, join(distDir, vendored), { recursive: true });
    await writeFile(join(distDir, spec.module), runtimeModule(join(distDir, spec.module, ".."), join(distDir, vendored, "dotnet.js")));
    return [vendored, spec.module];
  } finally {
    await rm(out, { recursive: true, force: true });
  }
}
